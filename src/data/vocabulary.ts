/**
 * Generate a complete vocabulary dataset that includes both main root words
 * and all secondary / related words (từ phụ, dạng từ: danh từ, tính từ, trạng từ...)
 */
export function getFullVocabularyList(includeSubWords: boolean = true): VocabItem[] {
  if (!includeSubWords) return VOCABULARY_LIST;

  const result: VocabItem[] = [];
  const seenWords = new Set<string>();

  for (const item of VOCABULARY_LIST) {
    const mainClean = item.word.trim().toLowerCase();
    if (!seenWords.has(mainClean)) {
      result.push(item);
      seenWords.add(mainClean);
    }

    // Expand secondary words (từ phụ, họ từ liên quan)
    if (item.relatedWords && item.relatedWords.length > 0) {
      item.relatedWords.forEach((rw, idx) => {
        const subClean = rw.word.trim();
        if (!subClean || seenWords.has(subClean.toLowerCase())) return;
        seenWords.add(subClean.toLowerCase());

        result.push({
          id: `${item.id}-sub-${idx}`,
          word: subClean,
          pos: rw.pos,
          ipa: rw.ipa || '',
          meaning: rw.meaning,
          section: item.section,
          sectionTitle: item.sectionTitle,
          isSubWord: true,
          rootWord: item.word,
          grammarNote: `Từ phụ / Dạng từ của gốc "${item.word}"`,
          example: item.example,
          exampleMeaning: item.exampleMeaning,
          relatedWords: [
            { word: item.word, pos: item.pos, ipa: item.ipa, meaning: item.meaning },
            ...(item.relatedWords || []).filter((other) => other.word.toLowerCase() !== subClean.toLowerCase()),
          ],
        });
      });
    }
  }

  return result;
}

export const ALL_FULL_VOCABULARY: VocabItem[] = getFullVocabularyList(true);

